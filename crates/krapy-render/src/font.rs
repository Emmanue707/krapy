pub fn glyph_rows(ch: char) -> [u8; 8] {
    let c = ch as u32;
    if (GLYPH_FIRST as u32..=GLYPH_LAST as u32).contains(&c) {
        GLYPHS[(c - GLYPH_FIRST as u32) as usize]
    } else {
        [0u8; 8]
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn glyph_table_sanity() {
        assert_eq!(glyph_rows(' '), [0u8; 8]);
        let a = glyph_rows('A');
        assert_ne!(a, [0u8; 8]);
        assert_ne!(glyph_rows('9'), [0u8; 8]);
        let idx = (b'A' - GLYPH_FIRST) as usize;
        assert_eq!(glyph_rows('A'), GLYPHS[idx]);
    }
}
